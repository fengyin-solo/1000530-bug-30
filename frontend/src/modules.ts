/**
 * 业务模块台账（前端）：与后端 app/catalog.py 一一对应。
 * 各模块页面只保留自己的 key，字段、动作、状态、统计卡片文案都从这里取，
 * 避免某个页面改了口径、其它入口还是旧数字。
 */
export type ModuleMeta = {
  key: string
  label: string
  entity: string
  columns: string[]
  filterFields: string[]
  actions: string[]
  statuses: string[]
  fallbackStats: { label: string; value: number }[]
}

const meta = (
  key: string,
  label: string,
  entity: string,
  columns: string[],
  actions: string[],
  statuses: string[],
  fallbackStats: string[],
  filterCount = 3,
): ModuleMeta => ({
  key,
  label,
  entity,
  columns,
  filterFields: columns.slice(0, filterCount),
  actions,
  statuses,
  fallbackStats: fallbackStats.map((item) => ({ label: item, value: 0 })),
})

